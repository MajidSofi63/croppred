#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Script 01: Prepare Data for India Crop Recommendation System
Purpose:
  - Load the real district-level crop dataset (district_apy.csv) without
    accidentally re-reading this pipeline's own output files.
  - Drop the "Total" season because it is a roll-up of Kharif + Rabi, not a
    real planting season. Keeping it would double-count the same harvest.
  - Collapse duplicate (state, district, year, season, crop) rows by summing
    area and production, then recompute yield from the sums.
  - Winsorise extreme yields per crop at the 1st/99th percentile.
  - Save data/crop_data_prepared.csv for Step 2.
"""

# Import operating-system helpers (not used for heavy logic, kept for clarity).
import os
# Import sys so we can exit with a non-zero code on fatal errors.
import sys
# Import pandas for tabular data manipulation.
import pandas as pd
# Import numpy for numeric helpers.
import numpy as np
# Import pathlib so all file paths are explicit and OS-independent.
from pathlib import Path

# Resolve the folder containing this script (the scripts/ directory).
SCRIPT_DIR = Path(__file__).resolve().parent
# Resolve the project root (the crop-recommendation-india/ directory).
PROJECT_ROOT = SCRIPT_DIR.parent
# Resolve the data directory.
DATA_DIR = PROJECT_ROOT / "data"

# Files produced by this pipeline. They must never be auto-detected as inputs,
# otherwise the script silently reads its own previous output.
GENERATED_FILES = {
    "crop_data_prepared.csv",  # Output of this script.
    "crop_data_with_weather.csv",  # Output of Step 2.
    "crop_data_with_weather2.csv",  # Legacy junk file from an earlier run.
    "district_coords.csv",  # Output of the coordinate builder.
    "district_coords_new.csv",  # Temporary coordinate scratch file.
}

# The preferred real source dataset. Explicit preference removes alphabetical
# accidents (previously crop_data_prepared.csv sorted first and was re-read).
PREFERRED_SOURCE = "district_apy.csv"

# Crops whose source production unit is not tonnes, which makes the derived
# t/ha value meaningless. They are excluded with an explicit reason.
EXCLUDED_CROPS = {
    "Coconut": "production is reported in nuts, not tonnes, so t/ha is invalid",
}

# A hard physical sanity bound for field-crop yields (t/ha). This is a safety
# net, not the main outlier treatment (which is per-crop 1st/99th winsorisation).
MAX_PLAUSIBLE_YIELD = 250.0

# Canonical season names used by the rest of the pipeline.
CANONICAL_SEASONS = {
    "kharif": "Kharif",
    "rabi": "Rabi",
    "summer": "Summer",
    "autumn": "Autumn",
    "winter": "Winter",
    "whole year": "Whole Year",
}


def find_dataset() -> Path:
    """Return the single input dataset path, preferring district_apy.csv."""
    # Collect every CSV/Excel candidate in data/.
    candidates = sorted(
        list(DATA_DIR.glob("*.csv"))
        + list(DATA_DIR.glob("*.xlsx"))
        + list(DATA_DIR.glob("*.xls"))
    )
    # Keep only files that are not generated by this pipeline.
    candidates = [p for p in candidates if p.name.lower() not in GENERATED_FILES]
    # Return the preferred source when it is present.
    preferred = DATA_DIR / PREFERRED_SOURCE
    if preferred.exists():
        return preferred
    # Otherwise return the first remaining candidate.
    if candidates:
        return candidates[0]
    # Fail loudly instead of silently doing nothing.
    print("[ERROR] No input dataset found in data/.")
    print(f"[ACTION] Place the real CSV/Excel dataset in: {DATA_DIR}")
    sys.exit(1)


def load_dataset(path: Path) -> pd.DataFrame:
    """Load a CSV or Excel file, trying common encodings for CSV."""
    # Branch on the file extension.
    if path.suffix.lower() == ".csv":
        # Try UTF-8 first because the real dataset uses it.
        try:
            return pd.read_csv(path, encoding="utf-8")
        except UnicodeDecodeError:
            # Fall back to Latin-1 if UTF-8 fails.
            try:
                return pd.read_csv(path, encoding="latin-1")
            except UnicodeDecodeError:
                # Last resort: Windows code page 1252.
                return pd.read_csv(path, encoding="cp1252")
    # Excel files are read with the default engine.
    if path.suffix.lower() in {".xlsx", ".xls"}:
        return pd.read_excel(path)
    # Any other extension is unsupported.
    print(f"[ERROR] Unsupported file format: {path.suffix}")
    sys.exit(1)


def standardise_columns(df: pd.DataFrame) -> pd.DataFrame:
    """Map real-world column names onto the pipeline's canonical names."""
    # Lower-case, trim, and snake-case every column name.
    df = df.copy()
    df.columns = (
        df.columns.str.strip()
        .str.lower()
        .str.replace(r"\s+", "_", regex=True)
    )
    # Define a lookup from canonical name to possible source names.
    synonyms = {
        "state": ["state", "state_name", "stname"],
        "district": ["district", "district_name", "distname", "dist_name"],
        "year": ["year", "crop_year", "agricultural_year"],
        "season": ["season", "season_name"],
        "crop": ["crop", "crop_name"],
        "area_ha": ["area", "area_ha", "area(ha)", "area_hectare"],
        "production_t": ["production", "production_t", "production(tonnes)"],
    }
    # Build the rename map by finding the first matching source column.
    rename_map = {}
    for canonical, options in synonyms.items():
        for option in options:
            if option in df.columns and option not in rename_map.values():
                rename_map[option] = canonical
                break
    # Apply the rename map.
    df = df.rename(columns=rename_map)
    # Verify the required columns are present.
    required = ["state", "district", "year", "season", "crop", "area_ha", "production_t"]
    missing = [c for c in required if c not in df.columns]
    if missing:
        print(f"[ERROR] Missing required columns after mapping: {missing}")
        print(f"[INFO] Columns found: {list(df.columns)}")
        sys.exit(1)
    # Return a frame with only the required columns, in a stable order.
    return df[required]


def clean_rows(df: pd.DataFrame) -> pd.DataFrame:
    """Clean names, parse years, remove invalid rows, and normalise seasons."""
    df = df.copy()
    # Trim categorical text.
    df["state"] = df["state"].astype(str).str.strip()
    df["district"] = df["district"].astype(str).str.strip()
    # Collapse repeated internal spaces in district names.
    df["district"] = df["district"].str.replace(r"\s+", " ", regex=True)
    # Keep districts upper-case to match the coordinate cache.
    df["district"] = df["district"].str.upper()
    # Title-case state names for readable display.
    df["state"] = df["state"].str.title()
    # Title-case crop names and collapse whitespace.
    df["crop"] = df["crop"].astype(str).str.strip().str.title()
    df["crop"] = df["crop"].str.replace(r"\s+", " ", regex=True)
    # Trim season text and remove the trailing space present in the raw file.
    df["season"] = df["season"].astype(str).str.strip()
    # Map season spellings onto canonical names (e.g. "Whole year" -> "Whole Year").
    df["season"] = df["season"].str.lower().map(CANONICAL_SEASONS).fillna(df["season"].str.title())
    # Parse the first four digits of the year (e.g. "1998-99" -> 1998).
    df["year"] = pd.to_numeric(
        df["year"].astype(str).str.extract(r"(\d{4})")[0],
        errors="coerce",
    )
    # Coerce numeric measures; bad strings become NaN.
    df["area_ha"] = pd.to_numeric(df["area_ha"], errors="coerce")
    df["production_t"] = pd.to_numeric(df["production_t"], errors="coerce")
    # Keep only plausible agricultural years; this drops the stray "0" year.
    valid_year = df["year"].between(1990, 2035)
    # Keep only positive area and production.
    valid_measure = (df["area_ha"] > 0) & (df["production_t"] > 0)
    # Keep recognised seasons plus "Total" so it can be counted and dropped.
    allowed_seasons = set(CANONICAL_SEASONS.values()) | {"Total"}
    valid_season = df["season"].isin(allowed_seasons)
    # Combine the masks.
    before = len(df)
    df = df[valid_year & valid_measure & valid_season].copy()
    # Report how many rows were removed by the validity filters.
    print(f"[INFO] Dropped {before - len(df)} invalid/missing rows")
    # Compute yield from the (still possibly duplicated) totals.
    df["yield_t_ha"] = df["production_t"] / df["area_ha"]
    # Return the cleaned frame.
    return df


def collapse_duplicates(df: pd.DataFrame) -> pd.DataFrame:
    """
    Collapse duplicate business keys.

    The raw source contains 5,282 duplicated (state, district, year, season,
    crop) keys with different area/production values. Treating them as separate
    observations would double-count the same harvest. Summing area and
    production and recomputing yield is the correct aggregation for this data.
    """
    # Count the duplicates before collapsing.
    key = ["state", "district", "year", "season", "crop"]
    duplicate_rows = int(df.duplicated(subset=key, keep=False).sum())
    print(f"[INFO] Rows participating in duplicate keys: {duplicate_rows}")
    # Sum the additive measures per business key.
    grouped = (
        df.groupby(key, as_index=False)
        .agg(area_ha=("area_ha", "sum"), production_t=("production_t", "sum"))
    )
    # Recompute yield from the summed totals rather than averaging yields.
    grouped["yield_t_ha"] = grouped["production_t"] / grouped["area_ha"]
    # Reorder columns for readability.
    grouped = grouped[key + ["area_ha", "production_t", "yield_t_ha"]]
    # Report the collapsed row count.
    print(f"[INFO] Collapsed {len(df)} rows into {len(grouped)} unique records")
    # Return the collapsed frame.
    return grouped


def winsorise_yields(df: pd.DataFrame) -> pd.DataFrame:
    """Clip extreme yields to the 1st/99th percentile within each crop."""
    df = df.copy()
    # Track how many values are changed.
    affected = 0
    # Apply the clipping crop by crop.
    for crop_name, group in df.groupby("crop"):
        # Skip crops with too few observations to estimate percentiles.
        if len(group) <= 10:
            continue
        # Compute the robust bounds.
        p01 = group["yield_t_ha"].quantile(0.01)
        p99 = group["yield_t_ha"].quantile(0.99)
        # Count the values that will move.
        affected += int((group["yield_t_ha"] < p01).sum())
        affected += int((group["yield_t_ha"] > p99).sum())
        # Clip using the crop mask.
        mask = df["crop"] == crop_name
        df.loc[mask, "yield_t_ha"] = df.loc[mask, "yield_t_ha"].clip(lower=p01, upper=p99)
    # Report the total number of clipped values.
    print(f"[INFO] Winsorised {affected} yield values at the 1st/99th percentile per crop")
    # Return the clipped frame.
    return df


def main() -> pd.DataFrame:
    """Run the full Step 1 pipeline and save the prepared CSV."""
    # Print a clear banner so the pipeline step is obvious in logs.
    print("=" * 80)
    print("STEP 1: PREPARE DATA")
    print("=" * 80)
    # Locate the real input file.
    dataset_path = find_dataset()
    print(f"[INFO] Input dataset: {dataset_path.name}")
    # Load it.
    raw = load_dataset(dataset_path)
    # Report the real shape.
    print(f"[INFO] Raw rows: {len(raw):,} | raw columns: {len(raw.columns)}")
    # Map column names.
    mapped = standardise_columns(raw)
    # Clean names, years, and measures.
    cleaned = clean_rows(mapped)
    # Report the season counts, including the roll-up row count.
    print("[INFO] Season counts after cleaning:")
    print(cleaned["season"].value_counts().to_string())
    # Drop the "Total" roll-up season explicitly.
    total_rows = int((cleaned["season"] == "Total").sum())
    cleaned = cleaned[cleaned["season"] != "Total"].copy()
    print(f"[INFO] Dropped {total_rows} 'Total' roll-up rows (Kharif+Rabi aggregate)")
    # Drop crops whose production unit makes the yield invalid.
    for crop_name, reason in EXCLUDED_CROPS.items():
        crop_rows = int((cleaned["crop"] == crop_name).sum())
        if crop_rows:
            cleaned = cleaned[cleaned["crop"] != crop_name].copy()
            print(f"[INFO] Dropped {crop_rows} '{crop_name}' rows: {reason}")
    # Collapse duplicated business keys.
    collapsed = collapse_duplicates(cleaned)
    # Apply the hard physical bound before the per-crop winsorisation.
    implausible = int((collapsed["yield_t_ha"] > MAX_PLAUSIBLE_YIELD).sum())
    if implausible:
        collapsed = collapsed[collapsed["yield_t_ha"] <= MAX_PLAUSIBLE_YIELD].copy()
        print(f"[INFO] Dropped {implausible} rows above {MAX_PLAUSIBLE_YIELD:.0f} t/ha")
    # Winsorise extreme yields.
    final = winsorise_yields(collapsed)
    # Print a compact final report.
    print("\n" + "=" * 80)
    print("DATA PREPARATION REPORT")
    print("=" * 80)
    print(f"[INFO] Years: {int(final['year'].min())} to {int(final['year'].max())}")
    print(f"[INFO] States: {final['state'].nunique()}")
    print(f"[INFO] State-district pairs: {final[['state', 'district']].drop_duplicates().shape[0]}")
    print(f"[INFO] Crops: {final['crop'].nunique()}")
    print(f"[INFO] Seasons: {sorted(final['season'].unique().tolist())}")
    print(f"[INFO] Final rows: {len(final):,}")
    print(f"[INFO] Yield range: {final['yield_t_ha'].min():.4f} to {final['yield_t_ha'].max():.4f} t/ha")
    print("=" * 80)
    # Save to the canonical output path.
    output_path = DATA_DIR / "crop_data_prepared.csv"
    final.to_csv(output_path, index=False)
    print(f"[INFO] Saved prepared data to {output_path}")
    # Return the frame for interactive use.
    return final


# Run main only when executed as a script.
if __name__ == "__main__":
    main()
